export function lang() {
  return state.language === "en" ? "en" : "zh";
}

export function tx(scope) {
  return I18N[lang()][scope];
}

export function updateChromeLanguage() {
  const labels = tx("nav");
  for (const [id, label] of Object.entries(labels)) {
    const node = document.getElementById(`nav-${id}`);
    if (node) node.textContent = label;
  }
  const section = document.querySelector(".nav .section");
  if (section) section.textContent = labels.section;
  const search = document.getElementById("global-search");
  if (search) search.remove();
  document.documentElement.lang = lang() === "en" ? "en" : "zh-CN";
  document.querySelectorAll("[data-language]").forEach((button) => button.classList.toggle("active", button.dataset.language === lang()));
}
